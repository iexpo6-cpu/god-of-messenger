#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Local Asset Synchronizer for 신의 사자 RPG
Downloads and bundles visuals into src/public/assets/visuals/
Generates src/services/localVisualManifest.ts for 0ms instantaneous loading.
"""

import os
import sys
import json
import shutil
import urllib.request
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
SRC_PUBLIC = BASE_DIR / "src" / "public"
VISUALS_DIR = SRC_PUBLIC / "assets" / "visuals"
MANIFEST_FILE = BASE_DIR / "src" / "services" / "localVisualManifest.ts"
MAPPING_FILE = BASE_DIR / "scripts" / "image_mapping.json"

CATEGORY_SUBDIRS = {
    "monster": "monsters",
    "boss": "bosses",
    "item": "items",
    "character": "characters",
    "location": "locations",
    "skill": "skills"
}

def sanitize_filename(name: str) -> str:
    # Remove special chars and sanitize
    clean = "".join(c for c in name if c.isalnum() or c in ("-", "_", " ")).strip()
    return clean.replace(" ", "_")

def sync_assets():
    print("[Local Visual Sync] Initializing directories...")
    for subdir in CATEGORY_SUBDIRS.values():
        (VISUALS_DIR / subdir).mkdir(parents=True, exist_ok=True)

    if not MAPPING_FILE.exists():
        print(f"[Local Visual Sync] Mapping file not found: {MAPPING_FILE}")
        return

    with open(MAPPING_FILE, "r", encoding="utf-8") as f:
        entries = json.load(f)

    manifest = {}

    headers = {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'
    }

    for entry in entries:
        name = entry.get("name")
        cat = entry.get("category", "monster")
        subdir = CATEGORY_SUBDIRS.get(cat, "monsters")
        local_src = entry.get("localPath")
        url = entry.get("imageUrl")

        if not name or (not local_src and not url):
            continue

        safe_name = sanitize_filename(name)
        ext = ".jpg"
        if local_src and os.path.splitext(local_src)[1]:
            ext = os.path.splitext(local_src)[1].lower()
        elif url and "." in url.split("/")[-1]:
            ext = os.path.splitext(url.split("/")[-1])[1].lower()
            if not ext or len(ext) > 5:
                ext = ".jpg"

        dest_filename = f"{safe_name}{ext}"
        dest_path = VISUALS_DIR / subdir / dest_filename
        relative_web_path = f"assets/visuals/{subdir}/{dest_filename}"

        # 1. Copy from local source if available
        if local_src and os.path.isfile(local_src):
            print(f"  -> Copying from local: {name} -> {relative_web_path}")
            shutil.copy2(local_src, dest_path)
            manifest[name] = relative_web_path
        # 2. Or download from URL
        elif url:
            print(f"  -> Downloading from URL: {name} ({url}) -> {relative_web_path}")
            try:
                req = urllib.request.Request(url, headers=headers)
                with urllib.request.urlopen(req, timeout=15) as resp:
                    with open(dest_path, "wb") as f_out:
                        f_out.write(resp.read())
                manifest[name] = relative_web_path
            except Exception as e:
                print(f"     [WARN] Failed to download {url}: {e}")
                # Keep remote url if download fails
                pass

    # Generate TypeScript manifest
    manifest_ts = f"""/**
 * Auto-generated by scripts/sync_local_assets.py
 * Contains local bundled static asset paths for 0ms loading without internet dependency.
 */

export const LOCAL_VISUAL_MANIFEST: Record<string, string> = {json.dumps(manifest, ensure_ascii=False, indent=4)};

/**
 * Checks if a visual asset is available locally in public assets
 */
export const getLocalVisualPath = (name: string): string | null => {{
    if (!name) return null;
    return LOCAL_VISUAL_MANIFEST[name] || LOCAL_VISUAL_MANIFEST[name.trim()] || null;
}};
"""

    with open(MANIFEST_FILE, "w", encoding="utf-8") as f:
        f.write(manifest_ts)

    print(f"\n[Local Visual Sync] Successfully synced {len(manifest)} local visual assets!")
    print(f"[Local Visual Sync] Manifest written to: {MANIFEST_FILE}")

if __name__ == "__main__":
    sync_assets()
