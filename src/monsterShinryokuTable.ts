// 로컬 사용자 정의 신력 계통 저장소 키
const CUSTOM_SHINRYOKU_STORAGE_KEY = 'custom_monster_shinryoku_table';

/**
 * 로컬스토리지에 저장된 사용자 정의 신력 계통 불러오기
 */
export function getCustomMonsterShinryokuOverrides(): Record<string, string> {
    try {
        if (typeof window === 'undefined' || !window.localStorage) return {};
        const saved = localStorage.getItem(CUSTOM_SHINRYOKU_STORAGE_KEY);
        if (saved) {
            return JSON.parse(saved);
        }
    } catch (e) {
        console.error('Failed to load custom monster shinryoku overrides:', e);
    }
    return {};
}

/**
 * 몬스터의 신력 계통을 사용자가 직접 변경 및 저장
 */
export function setCustomMonsterShinryoku(monsterName: string, shinryokuType: string): void {
    try {
        if (typeof window === 'undefined' || !window.localStorage) return;
        const current = getCustomMonsterShinryokuOverrides();
        current[monsterName] = shinryokuType;
        localStorage.setItem(CUSTOM_SHINRYOKU_STORAGE_KEY, JSON.stringify(current));
    } catch (e) {
        console.error('Failed to save custom monster shinryoku override:', e);
    }
}

/**
 * 몬스터 이름 키워드를 분석하여 어울리는 신력 계통을 자동 추론 (공식 14대 계통 준수)
 */
export function inferShinryokuTypeFromName(name: string): string {
    const n = name.toLowerCase();

    // 1. 화염계
    if (/화염|불꽃|화룡|불|화산|홍련|마그마|용암|지옥마|불가사리|이프리트|살라맨더|피닉스|적룡|주작|기린|슈텐도지|호박|케르베로스/i.test(n)) {
        return "화염계";
    }
    // 2. 빙결계
    if (/빙결|얼음|설인|설녀|동토|서리|한기|빙하|동결|백사|백호|눈보라|프로스트|블리자드|극지/i.test(n)) {
        return "빙결계";
    }
    // 3. 전격계
    if (/전격|뇌전|번개|천둥|벼락|청룡|감전|뇌신|라이트닝|볼트|스파크|누에/i.test(n)) {
        return "전격계";
    }
    // 4. 질풍계 (바람 대신 질풍계)
    if (/바람|질풍|폭풍|돌풍|조류|날개|텐구|카마이타치|그리폰|독수리|매|토끼|허리케인|윈드|기류|그슨새|와이번/i.test(n)) {
        return "질풍계";
    }
    // 5. 대지계
    if (/대지|바위|골렘|산악|토착|거목|지석묘|두억시니|현무|타이탄|어스|노움|동굴|석괴|모래|사막|스카라베/i.test(n)) {
        return "대지계";
    }
    // 6. 광휘계 (신성 대신 광휘계)
    if (/신성|성소|천상|세라핌|천사|대천사|신수|해태|여와|공손헌원|환웅|빛|성휘|성스러운|홀리|발키리|치천사|은빛|광휘/i.test(n)) {
        return "광휘계";
    }
    // 7. 암흑계
    if (/암흑|어둠|심연|지옥|저승|귀신|원혼|흡혈|네크로|강시|마계|악마|타락|마녀|어둑시니|창귀|흑룡|루시퍼|데몬|임프|서큐버스/i.test(n)) {
        return "암흑계";
    }
    // 8. 해수계 (수속성/물)
    if (/해수|물|바다|강|늪|호수|수룡|캇파|악어|나일강|운디네|피오르드|소베크|세이렌|크라켄/i.test(n)) {
        return "해수계";
    }
    // 9. 초화계 (자연/식물)
    if (/초화|숲|식물|나무|덩굴|꽃|픽시|요정|버섯|풀|세계수|정령|화초|가시/i.test(n)) {
        return "초화계";
    }
    // 10. 강철계 (금속/기계)
    if (/강철|철|금속|태엽|톱니|기계|드론|로봇|사이보그|병정|강철이/i.test(n)) {
        return "강철계";
    }
    // 11. 태양계
    if (/태양|파라오|태양신|케프리|아폴론|일륜|호루스/i.test(n)) {
        return "태양계";
    }
    // 12. 월광계
    if (/달|월광|달빛|아르테미스|월침|바스테트/i.test(n)) {
        return "월광계";
    }
    // 13. 무기강화계 (무구, 전사, 기사, 직업형 적)
    if (/기사|전사|자객|검사|궁수|사무라이|낭인|암살자|병사|포수|부랑자|산적|도적|무림|소림|무당파|취권|밀수꾼|병마용/i.test(n)) {
        return "무기강화계";
    }

    // 14. 신체강화계 (기본 맹수 및 신체 기반 적 - 무속성 대체)
    return "신체강화계";
}

/**
 * 몬스터 이름으로 신력 계통을 조회하는 표준 함수
 * 순서: 로컬 사용자 오버라이드 -> 마스터 설정 테이블 -> 키워드 추론 -> 기본값(신체강화계)
 */
export function getMonsterShinryokuType(rawMonsterName: string): string {
    if (!rawMonsterName) return "신체강화계";

    // 몬스터 이름 정리 (접두어, 접미어 알파벳 제거)
    const cleanName = rawMonsterName
        .replace(/\[.*?\]\s*/g, '')
        .replace(/\s+[A-Z0-9]$/g, '')
        .trim();

    // 1. 로컬스토리지 사용자 정의 오버라이드 확인
    const overrides = getCustomMonsterShinryokuOverrides();
    if (overrides[cleanName]) return overrides[cleanName];
    if (overrides[rawMonsterName]) return overrides[rawMonsterName];

    // 2. 마스터 매핑 테이블 확인
    if (MONSTER_SHINRYOKU_MAP[cleanName]) return MONSTER_SHINRYOKU_MAP[cleanName];
    if (MONSTER_SHINRYOKU_MAP[rawMonsterName]) return MONSTER_SHINRYOKU_MAP[rawMonsterName];

    // 3. 부분 일치 확인
    for (const [key, type] of Object.entries(MONSTER_SHINRYOKU_MAP)) {
        if (cleanName.includes(key) || key.includes(cleanName)) {
            return type;
        }
    }

    // 4. 이름 기반 지능형 키워드 추론
    return inferShinryokuTypeFromName(cleanName);
}
